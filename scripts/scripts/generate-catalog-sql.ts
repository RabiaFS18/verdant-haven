/**
 * Prints an idempotent SQL upsert for the `products` table, generated from
 * src/data/catalog.ts so the website and the database never disagree.
 *
 *   node scripts/generate-catalog-sql.ts > supabase/sync-catalog.sql
 *
 * Running the output again later updates names, prices and descriptions but
 * deliberately leaves live `stock` untouched.
 */
import { catalog } from "../src/data/catalog.ts";

const q = (value: string | null | undefined) =>
  value == null ? "NULL" : `'${value.replaceAll("'", "''")}'`;

const live = catalog.filter((p) => ["indoor", "outdoor", "both"].includes(p.category));
const featured = new Set(
  [...live]
    .sort((a, b) => (b.reviews ?? 0) - (a.reviews ?? 0))
    .slice(0, 4)
    .map((p) => p.slug),
);

const rows = catalog.map(
  (p) =>
    `  (${[
      q(p.slug),
      q(p.name),
      q(p.description),
      p.price,
      q(p.category),
      q(p.light),
      q(p.water),
      p.rating ?? 0,
      p.reviews ?? 0,
      q(p.tag),
      q(p.imagePosition ?? "center"),
      p.stock,
      featured.has(p.slug),
    ].join(", ")})`,
);

console.log(`-- Generated by scripts/generate-catalog-sql.ts — do not edit by hand.
INSERT INTO public.products
  (slug, name, description, price, category, light, water, rating, reviews_count, tag, image_position, stock, is_featured)
VALUES
${rows.join(",\n")}
ON CONFLICT (slug) DO UPDATE SET
  name = EXCLUDED.name,
  description = EXCLUDED.description,
  price = EXCLUDED.price,
  category = EXCLUDED.category,
  light = EXCLUDED.light,
  water = EXCLUDED.water,
  rating = EXCLUDED.rating,
  reviews_count = EXCLUDED.reviews_count,
  tag = EXCLUDED.tag,
  image_position = EXCLUDED.image_position,
  is_featured = EXCLUDED.is_featured;`);
